function buildDocs() {
  const templateDocs = VISUAL_TEMPLATE_LIBRARY.flatMap((template) => [
    {
      _id: template.templateId,
      _type: "generatorTemplate",
      title: template.title,
      slug: { _type: "slug", current: template.slug },
      description: template.description,
      designFamily: "multi-service",
      visualPreset: template.visualPreset,
      motionPreset: template.motionPreset,
      styleNotes: template.styleNotes,
      outputType: "page",
      tokenDefinitions: TOKEN_DEFINITIONS,
      baseSections: template.baseSections,
      optionalSections: template.optionalSections,
      variationRules: ["visual-template-library"],
      sectionVariants: template.sectionVariants,
      status: "ready",
      devOnly: true,
    },
    {
      _id: template.programId,
      _type: "generatorProgram",
      title: `${template.title} Program`,
      slug: { _type: "slug", current: `${template.key}-program` },
      template: { _type: "reference", _ref: template.templateId },
      dataset: { _type: "reference", _ref: SHARED_DATASET_ID },
      programType: "service-pages",
      generationMode: "batch",
      routeBase: ROUTE_BASE,
      defaultSeoPattern: {
        title: template.title,
        description: `${template.title} untuk banyak jasa dengan struktur visual reusable di dataset development.`,
      },
      status: "ready",
      aiMode: "prepared",
      devOnly: true,
    },
  ]);

  return [SHARED_DATASET, ...templateDocs];
}

async function deleteIfExists(client, id) {
  try {
    await client.delete(id);
  } catch (error) {
    if (error && typeof error === "object" && "statusCode" in error && error.statusCode === 404) {
      return;
    }
    throw error;
  }
}

async function main() {
  const env = await loadSanityEnv();
  const dataset = `${env.NEXT_PUBLIC_SANITY_DATASET || ""}`.trim().toLowerCase();
  const tokenSource = env.SANITY_DEV ? "SANITY_DEV" : env.SANITY_AUTH_TOKEN ? "SANITY_AUTH_TOKEN" : null;

  if (dataset !== "development") {
    throw new Error(`Generator starter seeding is development-only. Received dataset: ${dataset || "<empty>"}.`);
  }

  if (!tokenSource) {
    throw new Error("Missing Sanity write token. Expected SANITY_DEV or SANITY_AUTH_TOKEN.");
  }

  const docs = buildDocs();
  const desiredIds = new Set(docs.map((doc) => doc._id));
  const cleanupIds = LEGACY_STARTER_IDS.filter((id) => !desiredIds.has(id));

  if (WRITE_MODE) {
    const client = await createSanityWriteClient();
    for (const id of cleanupIds) {
      await deleteIfExists(client, id);
    }
    for (const doc of docs) {
      await client.createOrReplace(doc);
    }
  }

  console.log(
    JSON.stringify(
      {
        ok: true,
        writeMode: WRITE_MODE,
        dataset,
        tokenSource,
        templateLibrary: VISUAL_TEMPLATE_LIBRARY.map((item) => item.key),
        sharedDatasetId: SHARED_DATASET_ID,
        routeBase: ROUTE_BASE,
        cleanupIds,
        upsertedIds: docs.map((doc) => doc._id),
      },
      null,
      2,
    ),
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
